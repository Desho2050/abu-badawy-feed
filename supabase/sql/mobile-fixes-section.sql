-- 11) تحقّقٌ مطبوع: نتائج في اللوح ورسائل في Running.
do $$
declare
  sect    record;
  seeded  integer;
  r       record;
  steps   text;
  url     text;
  cover   text;
  app_url text;
begin
  select layout, source_kind, items_source into sect
    from public.sections where id = 'mobile_fixes';

  if not found then
    raise warning 'WARNING: قسم mobile_fixes غير موجود — لن يظهر في درج التطبيق ولا في index.json.';
  else
    if sect.layout = 'fixes' then
      raise notice 'NOTICE: قسم حلول مشاكل الموبايل جاهز (layout=fixes, kind=%, items=%).',
        sect.source_kind, sect.items_source;
    else
      raise warning 'WARNING: تخطيط القسم «%» لا fixes — سيرسمه التطبيق قائمةَ أخبار عادية.',
        sect.layout;
    end if;
    if sect.source_kind <> 'json' or sect.items_source <> 'admin' then
      raise warning 'WARNING: القسم غير مُدار من اللوحة (kind=%, items=%) — لن يكتب الناشر ملفَّ عناصره.',
        sect.source_kind, sect.items_source;
    end if;
  end if;

  select count(*) into seeded from public.items
   where section_id = 'mobile_fixes' and status = 'published';

  if seeded = 0 then
    raise warning 'WARNING: لا حلَّ منشورٌ في القسم — تظهر شاشتُه «لا حلٌّ منشورٌ بعد».';
  else
    raise notice 'NOTICE: % حلٌّ منشور، ويكتبها الناشر في data/sections/mobile_fixes.json.', seeded;
  end if;

  for r in select slug, title, link, image, source_name, fields from public.items
            where section_id = 'mobile_fixes' and status = 'published' loop

    -- (أ) الخطوات: بلا حقلٍ غيرِ فارغٍ بطاقةٌ بلا حلّ — تُعرض المشكلةُ وحدها.
    steps := nullif(btrim(coalesce(r.fields->>'الخطوات', r.fields->>'الحل', r.fields->>'الطريقة', '')), '');
    if steps is null then
      raise warning 'WARNING: حلُّ «%» بلا «الخطوات»: بطاقتُه ستعرض المشكلةَ ولا تعرض لها مخرجًا.', r.title;
    elsif steps !~ '؛' and steps !~ '\n' and steps !~ '\|' then
      raise notice 'NOTICE: حلُّ «%» خطوةٌ واحدةٌ بلا فاصل: تُعرض سطرًا واحدًا مرقَّمًا.', r.title;
    end if;

    -- (ب) الشرح المصوَّر: بلا رابطٍ صالح لا زرَّ، فتبقى البطاقةُ نصًّا يُقرأ.
    url := coalesce(nullif(btrim(coalesce(r.link, '')), ''),
                    nullif(btrim(coalesce(r.fields->>'الفيديو', '')), ''));
    if url is null then
      raise notice 'NOTICE: حلُّ «%» بلا فيديو: لا زرَّ «شاهد فيديو الإصلاح» في بطاقتِه.', r.title;
    elsif url !~ '^https?://' then
      raise warning 'WARNING: رابط شرحِ «%» ليس http(s) فلا يُفتح: «%».', r.title, url;
    end if;

    -- (ج) الغلاف: مسارٌ نسبيٌّ داخل الموقع أو رابطٌ كامل، وإلا فلا صورة.
    cover := nullif(btrim(coalesce(r.image, '')), '');
    if cover is null then
      raise notice 'NOTICE: حلُّ «%» بلا صورة غلاف.', r.title;
    elsif cover !~ '^https?://' and cover !~ '^[A-Za-z0-9؀-ۿ._/-]+\.(svg|png|jpe?g|webp|gif|avif)$' then
      raise warning 'WARNING: صورةُ «%» ليست رابطًا كاملًا ولا مسارًا نسبيًّا صالحًا (%): لن تُعرض.', r.title, cover;
    end if;

    -- (د) النسبة: فيديو الشرح عند صاحبه، فاسمُه على البطاقة واجبٌ لا تزيين.
    if nullif(btrim(coalesce(r.source_name, '')), '') is null and url is not null then
      raise warning 'WARNING: حلُّ «%» ينشر فيديو بلا اسمِ صاحبه في source_name.', r.title;
    end if;

    -- (هـ) التطبيق: رابطُ متجرٍ في حقلٍ وحده، فاسمُه في «اسم التطبيق» يسمّي الزرَّ.
    app_url := nullif(btrim(coalesce(r.fields->>'التطبيق', r.fields->>'رابط التطبيق', '')), '');
    if app_url is null then
      raise notice 'NOTICE: حلُّ «%» بلا «التطبيق»: لا زرَّ تحميلٍ في بطاقتِه، وهذا مقبول.', r.title;
    elsif app_url !~ '^https?://' then
      raise warning 'WARNING: «التطبيق» في حلِّ «%» ليس http(s) فلا يفتح متجرًا: «%».', r.title, app_url;
    elsif nullif(btrim(coalesce(r.fields->>'اسم التطبيق', '')), '') is null then
      raise notice 'NOTICE: تطبيقُ حلِّ «%» بلا «اسم التطبيق»: زرُّه يُعرض «حمّل التطبيق» مبهَمًا.', r.title;
    end if;
  end loop;
end
$$;

