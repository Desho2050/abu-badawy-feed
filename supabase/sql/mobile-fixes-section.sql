       i.fields->>'النوع'  as category,
       i.fields->>'السبب'  as cause,
       i.link              as video,
       coalesce(i.fields->>'التطبيق', i.fields->>'رابط التطبيق') as app,
       i.fields->>'اسم التطبيق'  as app_name,
       i.image             as cover,
       i.source_name,
       (select count(*) from regexp_split_to_table(coalesce(i.fields->>'الخطوات',''), '؛') as s(step)
          where btrim(s.step) <> '') as steps_count,
       i.status
  from public.items i
 where i.section_id = 'mobile_fixes'
 order by i.published_at desc nulls last, i.sort_order desc;
