-- قيد يمنع تكرار الخبر الآلي: لا يُخزَّن نفس الslug مرتين في القسم.
--
-- السبب: نسخة ٢٠٢٦-١٠-٠٤ من sync-news.mjs فلترت العناصر الموجودة بـ
--   slug=like.rss.*   ← يفسّرها PostgREST LIKE 'rss.%'، والـslug يبدأ «rss-» لا «rss.»
-- فلم ترَ أي عنصر قائم، وأدخلت كل جولة نسخة ثانية من الأخبار الستين نفسها.
-- القيد وحده يمنع عودة الخطأ بصمت؛ بدونه يُنتج أي خلل لاحق في الفلترة
-- بطاقات مكرّرة في التطبيق.
--
-- القيد جزئي (where slug like 'rss-%') لأن العناصر اليدوية تترك slug فارغًا أو
-- تختار ما يشاء، ولا يجوز أن يمنعها.
--
-- رتِّب التشغيل: شغّل جولة مزامنة واحدة تحذف المكرّرات أولًا (Actions ←
-- «مزامنة الأخبار العالمية والرياضية» ← Run workflow)، ثم نفّذ هذا الملف.
-- إن نفّذته قبل التنظيف فسيرفض، لأن هناك مكرّرات فعلية الآن.
-- ─────────────────────────────────────────────────────────────────────────────

-- الوقوف على المكرّرات قبل الإنشاء (استعلام فحص، لا يغيّر شيئًا).
select section_id, slug, count(*) as نسخ, max(updated_at) as أحدث
from public.items
where slug like 'rss-%'
group by section_id, slug
having count(*) > 1
order by نسخ desc;
-- إن خرجت صفوف أعلاه: شغّل جولة مزامنة تحذفها، ثم أعد المحاولة هنا.

create unique index if not exists items_rss_slug_key
  on public.items (section_id, slug)
  where slug like 'rss-%';

-- فحص نهائي: القيد موجود، ولا مكرّر.
select indexname, indexdef
from pg_indexes
where tablename = 'items' and indexname = 'items_rss_slug_key';
