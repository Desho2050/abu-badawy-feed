-- 3) تحقّق مطبوع: نتائج في اللوح ورسائل في Running.
--    أهمها فحصان خاصان بهذا القسم: لا عنصر بلا مصدر، ولا صورة بلا نسب.
do $$
declare
  sect      record;
  total     integer;
  published integer;
  no_source integer;
  no_credit integer;
  bad_link  integer;
begin
  select layout, source_kind, items_source into sect
    from public.sections where id = 'governorate';

  if not found then
    raise warning 'WARNING: قسم governorate غير موجود — لن يظهر في درج التطبيق.';
  else
    raise notice 'NOTICE: قسم محافظة كفر الشيخ جاهز (layout=%, kind=%, items=%).',
      sect.layout, sect.source_kind, sect.items_source;
  end if;

  select count(*) into total     from public.items where section_id = 'governorate';
  select count(*) into published from public.items where section_id = 'governorate' and status = 'published';

  if published >= 20 then
    raise notice 'NOTICE: % عنصرًا منشورًا من أصل %، والناشر يكتبها في data/sections/governorate.json.', published, total;
  else
    raise warning 'WARNING: العناصر المنشورة % من % (المتوقع 20) — أعد تشغيل الملف أو انشر الناقص من اللوحة.', published, total;
  end if;

  -- لا عنصر بغير مصدر: كل عنصر يجب أن يحمل source_name وsource_url إلى ويكيبيديا.
  select count(*) into no_source from public.items
   where section_id = 'governorate'
     and status = 'published'
     and (coalesce(source_name, '') = ''
          or coalesce(source_url, '') !~* '^https://ar\.wikipedia\.org/wiki/');

  if no_source > 0 then
    raise warning 'WARNING: % عنصرًا منشورًا بلا مصدر ويكيبيديا صحيح — املأ «اسم المصدر» و«رابط المصدر».', no_source;
  else
    raise notice 'NOTICE: كل عنصر منشور يذكر مصدره في ويكيبيديا العربية.';
  end if;

  -- لا صورة كومنز بغير نسب: النسب إلزامي احترامًا للرخصة، والتطبيق يعرضه تحت الصورة.
  select count(*) into no_credit from public.items
   where section_id = 'governorate'
     and coalesce(image, '') like '%upload.wikimedia.org%'
     and coalesce(image_credit, '') = '';

  if no_credit > 0 then
    raise warning 'WARNING: % صورة من كومنز بلا حقل النسب — الرخصة الحرة توجب الذكر.', no_credit;
  else
    raise notice 'NOTICE: كل صورة في القسم تحمل نسب المرخّص ورخصة كومنز.';
  end if;

  -- زر «افتح المصدر» في التطبيق لا يظهر إلا لرابط مطلق بصيغة صحيحة.
  select count(*) into bad_link from public.items
   where section_id = 'governorate'
     and status = 'published'
     and coalesce(link, '') !~* '^https://(ar\.wikipedia\.org|web\.archive\.org)/';

  if bad_link > 0 then
    raise warning 'WARNING: % عنصرًا رابطه ليس مقالة ويكيبيديا أو نسخة مؤرشفة — راجعه.', bad_link;
  else
    raise notice 'NOTICE: أزرار فتح المصادر تعمل: كلها روابط https لويكيبيديا أو للأرشيف.';
  end if;
end $$;

