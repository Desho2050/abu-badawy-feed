-- ─────────────────────────────────────────────────────────────────────────────
-- محو العناصر المُختلَعة التي يبذرُها seed-content.sql
--
-- البذرُ الأولي كان يعرض أمثلةً تحريرية على أنها خبر حقيقي: «فريق القرية يفوز
-- في دوري المنطقة» برابط إلى example.com، و«افتتاح مخبز آلي» برقم هاتف
-- «01xxxxxxxxx»، و«تمور البلدية» بسعر «…». القارئ لا يرى قالبًا — يرى خبرًا
-- وعرضًا في قريةٍ حقيقية، فإما اتصل برقمٍ لا وجود له وإما صدّق حدثًا لم يقع.
-- التطبيقُ يعرض حالة «لا عناصر بعد» للأقسام الفارغة، فالمحوُ آمنٌ ولا شاشةَ تتعطل.
--
-- التشغيل: لوحة Supabase → SQL Editor → الصق كلَّ التنفيذيات → Run.
-- التكرارُ آمن (delete where slug in … لا يرمي خطأً إن لم يجد صفًّا).
--
-- البذرُ لا يُعيدها بعد هذا: tools/gen-seed-sql.mjs يتخطّى هذه المعرّفات
-- (PLACEHOLDER_ITEM_SLUGS في tools/content-model.mjs)، ومِشْبَك التحقق:
--   node tools/verify-sql.mjs
-- ─────────────────────────────────────────────────────────────────────────────

begin;

-- أخبار وعروض وإعلانات مُختلَعة — تُنسى وتُمحى
delete from public.items
where slug in (
  'vn-1', 'vn-2', 'vn-3',   -- أخبار القرية
  'wn-1', 'wn-2',           -- أخبار عالمية (رابطا example.com)
  'sp-1', 'sp-2',           -- رياضة: نتيجة مباراة مخترعة + رابط example.com
  'ad-1', 'ad-2',           -- عروض: رقم هاتف وهمي ومكان «المكان والمواعيد»
  'of-1', 'of-2'            -- أسواق: «… ج.م / كيلو» و«01xxxxxxxxx»
);

-- اختياري: بقايا البذر التعليمي (معالم وشخصيات بأجساد فارغة). ليست أخبارًا ولا
-- أرقامَ تواصل، بل عناوينُ يعرف المحرر أنه لم يكتبها بعد — تُترك إن أردتَ إطارًا
-- تبني عليه، وتُمحى بهذا السطر إن أردتَ الأقسامَ فارغةً تمامًا:
-- delete from public.items where slug in ('fg-1', 'fg-2', 'lm-mosque', 'lm-school', 'lm-water');

commit;

-- تحقّق: لا صفَّ مختلَعًا بقي ولا رابط example.com في الجدول كلّه
select slug, section_id, title
from public.items
where slug in ('vn-1','vn-2','vn-3','wn-1','wn-2','sp-1','sp-2','ad-1','ad-2','of-1','of-2')
   or link like '%example.com%'
   or source_url like '%example.com%'
order by section_id, slug;

-- عدّادُ ما تبقى لكل قسم، حتى تعرف ما الذي صارت شاشته فارغة:
select section_id, count(*) as items
from public.items
group by section_id
order by section_id;
