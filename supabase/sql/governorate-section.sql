-- مع ذكر المصدر في كل عنصر (اسم المصدر + رابط المقالة + حقوق الصورة في النسب).
--
-- لا DDL هنا إطلاقًا: التخطيط مستخدم بالفعل (list) والمصدر من اللوحة (json/admin)،
-- فيكتب الناشر الملف data/sections/governorate.json من تلقاء نفسه في جولة */5 القادمة.
-- إذن بعد التشغيل: لا شيء في انتظار جولة الناشر ثم تحديث التطبيق.
--
-- كل عنصر = جانب واحد من معلومات المحافظة (الموقع، السكان، التقسيم، التاريخ الإداري،
-- الاقتصاد، الجامعة، البحيرة، المصيف، المعركة، دسوق، العاصمة، الطرق، المركز، الأعلام،
-- المحافظون، بطاقة سريعة) — وهذا هو اختيار «قائمة: عنصر لكل جانب».
--
-- الصور كلها من ويكيميديا كومنز برخصة حرة، وروابطها وأسماء مرخّصيها متحققة من واجهة
-- كومنز في 2026-10-04، والنسب مكتوب في image_credit فيعرضه التطبيق تحت الصورة دائمًا.
-- الصُوَر المستخدَمة مصغّرات بعرض 960 بكسل (لا الأصول الكبيرة) لتخفّ على اتصال القرية؛
-- وكومنز لا يخدم كل عرض عشوائي بل يقبل مقاساته المعلنة، فأي تغيير في المقاس يستلزم
-- التحقق من الرابط بالفتح قبل النشر.
-- نص العناصر ملخَّص عن المقالات لا منسوخ منها، احترامًا لترخيص CC BY-SA 4.0 الذي يلزم
-- بالنسب؛ لذلك كل عنصر فيه جملة «المصدر» في آخر متنه، وزر «افتح المصدر» في التطبيق.
--
-- أرقام اختيرت بعناية بعد تضارب في المصدر نفسه:
--   السكان: 3,740,624 (تقدير 1/1/2024 للجهاز المركزي للتعبئة والإحصاء) هو المعتمد،
--            مع ذكر أن مقالة ويكيبيديا تنقل عن 2015 رقمين (3,172,753 في الصندوق
--            و3,941,293 في المتن)، لأن الواجب أمانة لا اختيار.
--   المدن: 13 مدينة في المتن مقابل 14 في صندوق المعلومات، فذُكر الاثنان.
--   بوغاز البرلس: 44 مترًا في مقالة المحافظة مقابل نحو 250 مترًا عرضًا في مقالة البحيرة.
--
-- آمن للتكرار: القسم يُنشأ أو يُحدَّث (on conflict)، وكل عنصر له insert مستقل
-- بشرط where not exists على الslug، فلا تتضاعف البذور عند إعادة التشغيل.
-- نفّذه في Supabase ← SQL Editor ← New query ← الصق ← Run (مشروع DeshoStore).

